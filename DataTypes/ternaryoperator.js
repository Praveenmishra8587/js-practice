//?: ternaryoperator - is a conditional operator that evaluates a condition and returns one of two values based on whether the condition is true or false. It is often used as a shorthand for an if-else statement.

//Syntax: condition ? value_if_true : value_if_false

let num = 100;
let bill = num>=300 ? 100:200;
console.log(bill);

let age =17;

let isEligible = age>=18 ? "You are eligible to vote" : "You are not eligible to vote";
console.log(isEligible);